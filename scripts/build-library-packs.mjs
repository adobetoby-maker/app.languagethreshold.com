// Build from the authoritative authored seeds; never maintain parallel content.
import { build } from "esbuild";
import { format, resolveConfig } from "prettier";
import { mkdir, writeFile, rm } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";
import { createHash } from "node:crypto";
export async function generateLibraryPacks() {
  const result = await build({
    stdin: {
      contents:
        'export { ALL_SEEDS } from "./src/data/all-seeds"; export { planLibraryPacks } from "./src/data/library-pack-plan";',
      resolveDir: process.cwd(),
      sourcefile: "library-pack-entry.ts",
    },
    bundle: true,
    write: false,
    format: "esm",
    platform: "node",
    tsconfig: "tsconfig.json",
  });
  const { ALL_SEEDS, planLibraryPacks } = await import(
    `data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString("base64")}`
  );
  const languages = [...new Set(ALL_SEEDS.map((e) => e.language))].sort();
  const plan = planLibraryPacks(ALL_SEEDS);
  await rm("src/data/generated-library", { recursive: true, force: true });
  await mkdir("src/data/generated-library", { recursive: true });
  // Partition by shared ownership: overlapping modules import the same chunks,
  // rather than embedding duplicate copies of a passage in many module bundles.
  const shards = [];
  const shardHashes = [];
  const packShards = {};
  for (const language of languages) {
    const packs = Object.fromEntries(
      Object.entries({ core: plan.core, ...plan.modules }).map(([id, entries]) => [
        id,
        new Set(entries.filter((entry) => entry.language === language).map((entry) => entry.id)),
      ]),
    );
    const groups = new Map();
    for (const entry of ALL_SEEDS.filter((entry) => entry.language === language)) {
      const owners = Object.keys(packs).filter((id) => packs[id].has(entry.id));
      if (!owners.length) throw new Error(`Reading has no core/module assignment: ${entry.id}`);
      const key = JSON.stringify(owners);
      if (!groups.has(key)) groups.set(key, []);
      groups.get(key).push(entry);
    }
    for (const id of Object.keys(packs)) packShards[`${language}/${id}`] = [];
    for (const [owners, entries] of groups) {
      const content = JSON.stringify(entries);
      const hash = createHash("sha256").update(content).digest("hex").slice(0, 16);
      await writeFile(`src/data/generated-library/${hash}.json`, content);
      const index = shards.length;
      shardHashes.push(hash);
      shards.push(
        `  () => import("./generated-library/${hash}.json").then(m => m.default as LibraryEntry[]),`,
      );
      for (const id of JSON.parse(owners)) packShards[`${language}/${id}`].push(index);
    }
  }
  await writeFile(
    "src/data/library-pack-loaders.ts",
    await format(
      `// Generated by scripts/build-library-packs.mjs.\nimport type { LibraryEntry } from "@/state/library-state";\nconst SHARDS = [\n${shards.join("\n")}\n];\nexport const LIBRARY_PACK_SHARDS: Record<string, number[]> = ${JSON.stringify(packShards)};\nexport const LIBRARY_PACK_LOADERS: Record<string, () => Promise<LibraryEntry[]>> = Object.fromEntries(Object.entries(LIBRARY_PACK_SHARDS).map(([key, indices]) => [key, async () => (await Promise.all(indices.map(index => SHARDS[index]()))).flat()]));\n`,
      { ...(await resolveConfig("src/data/library-pack-loaders.ts")), parser: "typescript" },
    ),
  );
  await writeFile(
    "src/data/library-pack-manifest.json",
    JSON.stringify(
      Object.fromEntries(
        Object.entries(packShards).map(([key, indices]) => [
          key,
          indices.map((index) => shardHashes[index]),
        ]),
      ),
      null,
      2,
    ) + "\n",
  );
  return { ALL_SEEDS, languages };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href)
  await generateLibraryPacks();
