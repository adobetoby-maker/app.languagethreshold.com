function dedupeByChar(list: CjkCharacter[]): CjkCharacter[] {
  const seen = new Set<string>();
  const out: CjkCharacter[] = [];
  for (const item of list) {
    if (seen.has(item.char)) continue;
    seen.add(item.char);
    out.push(item);
  }
  return out;
}

