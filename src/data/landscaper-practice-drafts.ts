import type { LessonWord } from "./curriculum.ts";

/** Original English/Spanish practice drafts. No language/domain approval or technical certification. */
export interface LandscaperLessonDraft {
  n: number;
  objective: string;
  words: LessonWord[];
  reading: { title: string; es: string[]; en: string[] };
}
function pair(row: string): [string, string] {
  const parts = row.split("|");
  if (parts.length !== 2 || parts.some((value) => !value.trim()))
    throw new Error("Invalid public lesson draft pair.");
  return [parts[0], parts[1]];
}
function draft(
  n: number,
  title: string,
  objective: string,
  terms: string[],
  phrases: string[],
  scene: string[],
  closing: string,
): LandscaperLessonDraft {
  const termPairs = terms.map(pair),
    phrasePairs = phrases.map(pair);
  const sentences = [...scene.map(pair), ...phrasePairs, pair(closing)];
  return {
    n,
    objective,
    words: [
      ...termPairs.map(([es, en]) => ({ es, en, kind: "term" as const })),
      ...phrasePairs.map(([es, en]) => ({ es, en, kind: "phrase" as const })),
    ],
    reading: { title, es: sentences.map(([es]) => es), en: sentences.map(([, en]) => en) },
  };
}

