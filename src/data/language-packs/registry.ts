// Built by TAC — 2026-11-21
// The language-pack registry (language-pack model section 5; the model calls this file index.ts).
// The one place the app learns which languages exist and how each one behaves. Ask a pack, never
// compare a language name or code.
//
//   getPack(code)              the pack for a code; throws for an unknown code (never substitutes)
//   packFor(codeOrName)        the pack for a code or a stored legacy name ("Spanish"); null if none
//   requirePackFor(codeOrName) same, but throws
//   listedPacks(qa)            packs a learner may choose (draft packs only in a QA build)
//   LANGUAGE_CODES             every registered code, for zod enums and Records
//
// Sources: the bundled packs (./bundled.ts, generated by scripts/import-language-packs.mjs), then
// the legacyPack adapter (./legacy.ts) for every PWA target without a registered bundled pack. A
// draft pack (French and Italian today) is registered only in a QA build (VITE_LT_QA=1); a normal
// build keeps that language's legacy adapter, so a normal learner never sees draft content or rules.

import { isQaBuild } from "../../lib/qa-build.ts";
import { appCodesWith, withAppCorrections } from "./app-data.ts";
import { BUNDLED_PACKS } from "./bundled.ts";
import { legacyPacks } from "./legacy.ts";
import packIndex from "./packs.json" with { type: "json" };
import type { Availability, LanguagePack, PackIndexEntry } from "./types.ts";

export type {
  AccentMode,
  Availability,
  LanguagePack,
  PackIndexEntry,
  VerbFormKey,
} from "./types.ts";

/** A language code (ISO 639-1, optional script/region subtag): "es", "zh-Hans", "pt-PT". */
export type LanguageCode = string;

function assertPack(raw: unknown): LanguagePack {
  const pack = raw as LanguagePack;
  if (
    !pack ||
    pack.schemaVersion !== 1 ||
    typeof pack.code !== "string" ||
    typeof pack.name !== "string" ||
    !pack.status ||
    !pack.speech ||
    !pack.answerRules ||
    !pack.keyboard ||
    !pack.ids
  )
    throw new Error("A bundled language pack is not a schemaVersion 1 runtime pack");
  return pack;
}

/** True when a build may register (and so show) a pack of this availability. */
export function availabilityVisible(availability: Availability, qa = isQaBuild()): boolean {
  return (
    availability === "native" || availability === "online" || (qa && availability === "draft")
  );
}

const QA = isQaBuild();
const BUNDLED: readonly LanguagePack[] = BUNDLED_PACKS.map(assertPack)
  .filter((pack) => availabilityVisible(pack.status.availability, QA))
  .map(withAppCorrections);
const BUNDLED_CODES = new Set(BUNDLED.map((pack) => pack.code));

/** Every registered pack: visible bundled packs and legacy adapters, sorted by English name. */
export const PACKS: readonly LanguagePack[] = [...BUNDLED, ...legacyPacks(BUNDLED_CODES)].sort(
  (a, b) => a.name.localeCompare(b.name),
);

const BY_CODE = new Map(PACKS.map((pack) => [pack.code, pack] as const));
const BY_LEGACY = new Map(
  PACKS.flatMap((pack) => [pack.name, ...pack.legacyNames].map((name) => [name, pack] as const)),
);

/** Every registered code (for z.enum and Records). Never a hand-kept list. */
export const LANGUAGE_CODES = PACKS.map((pack) => pack.code) as [LanguageCode, ...LanguageCode[]];

/** The pack for a registered code. Throws for an unknown code; never substitutes another language. */
export function getPack(code: LanguageCode): LanguagePack {
  const pack = BY_CODE.get(code);
  if (!pack) throw new Error(`No language pack for "${code}"`);
  return pack;
}

/** Read-time migration of a stored display name ("Spanish") to its pack. */
export function packFromLegacyName(name: string): LanguagePack | undefined {
  return BY_LEGACY.get(name);
}

/**
 * The pack for a code or for a stored legacy name. Null for anything else (a native-only language
 * such as "Dutch", an empty value, a typo). Use it at the boundary where app state or a URL still
 * carries a display name, then pass the pack on.
 */
export function packFor(codeOrName: string | null | undefined): LanguagePack | null {
  if (!codeOrName) return null;
  return BY_CODE.get(codeOrName) ?? BY_LEGACY.get(codeOrName) ?? null;
}

/** packFor that throws: for state that must always name a registered target language. */
export function requirePackFor(codeOrName: string | null | undefined): LanguagePack {
  const pack = packFor(codeOrName);
  if (!pack) throw new Error(`No language pack for "${codeOrName ?? ""}"`);
  return pack;
}

/** The code of a code or legacy name, or null. */
export function packCodeOf(codeOrName: string | null | undefined): LanguageCode | null {
  return packFor(codeOrName)?.code ?? null;
}

/** True when two values (codes or legacy names) name the same registered language. */
export function sameLanguage(a: string | null | undefined, b: string | null | undefined): boolean {
  const pa = packFor(a);
  return Boolean(pa && pa === packFor(b));
}

/** Packs a learner may choose. Draft packs only when `qa` (default: this build's QA flag). */
export function listedPacks(qa = QA): LanguagePack[] {
  return PACKS.filter((pack) => availabilityVisible(pack.status.availability, qa));
}

/** True when this build registers the bundled pack (it has a catalog), not a legacy adapter. */
export function isBundledPack(pack: LanguagePack): boolean {
  return BUNDLED_CODES.has(pack.code) && BY_CODE.get(pack.code) === pack;
}

/** The index row of a bundled pack (modules and lesson counts), or null for a legacy adapter. */
export function packIndexEntry(pack: LanguagePack): PackIndexEntry | null {
  if (!isBundledPack(pack)) return null;
  return (packIndex as PackIndexEntry[]).find((entry) => entry.code === pack.code) ?? null;
}

/** "<Language> voice unavailable": the fail-closed label when a pack has no voice for a line. */
export function voiceUnavailableLabel(pack: LanguagePack): string {
  return `${pack.name} voice unavailable`;
}

/** The registered pack whose server fallback voice serves `code`, or null (fail closed). */
export function remoteFallbackPack(code: string | null | undefined): LanguagePack | null {
  const pack = code ? BY_CODE.get(code) : undefined;
  return pack?.speech.remoteFallback ? pack : null;
}

function soleAppPack(flag: "historicalCourse" | "workplaceCourse"): LanguagePack {
  const [code] = appCodesWith(flag);
  return getPack(code);
}

/**
 * The PWA's first course (its app file sets historicalCourse): modules written before packs are
 * authored in it, and stored state from before a language setting existed means it. Read it here;
 * never name it.
 */
export function historicalCoursePack(): LanguagePack {
  return soleAppPack("historicalCourse");
}

/** The language learnDirection "en-target" (English for Work) modules teach. */
export function workplaceCoursePack(): LanguagePack {
  return soleAppPack("workplaceCourse");
}

/**
 * The learning pair of records that carry none (team module assignments, core30Log entries and
 * profiles stored before a language setting existed): the historical course and its default native,
 * as stored names ("Spanish", "English").
 */
export function historicalCoursePair(): { target: string; native: string } {
  const pack = historicalCoursePack();
  const native = packFor(pack.native.default);
  return { target: pack.name, native: native?.name ?? pack.native.names[pack.native.default] ?? "" };
}
